-- جسور التسامح: جدول المشاركات وسياسات الحماية.
-- يمكن تشغيل هذا الملف أكثر من مرة دون تكرار السياسات.

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  role text not null check (role in ('student','parent','teacher')),
  message text not null check (char_length(message) between 8 and 280),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

alter table public.submissions enable row level security;

-- إزالة أسماء السياسات المستخدمة في النسخ السابقة ثم إنشاؤها مرة واحدة.
drop policy if exists "Allow pending submissions" on public.submissions;
drop policy if exists "Allow reading approved messages" on public.submissions;
drop policy if exists "public can submit pending messages" on public.submissions;
drop policy if exists "public can read approved messages" on public.submissions;

create policy "Allow pending submissions"
on public.submissions for insert to anon, authenticated
with check (status = 'pending');

create policy "Allow reading approved messages"
on public.submissions for select to anon, authenticated
using (status = 'approved');

grant select, insert on public.submissions to anon, authenticated;
grant usage, select on sequence public.submissions_id_seq to anon, authenticated;

-- لا تنشئ سياسة عامة لتعديل status أو حذف المشاركات.
